"""Embed the NORTHSTAR CSV files in assets/data.js so the pages work offline,
from a USB stick, or opened straight from disk (browsers block fetch() on file://).

Run from this folder after changing either CSV:   python3 build_data.py
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
out = ["// Generated by build_data.py from data/*.csv. Do not edit by hand."]
for var, name in [("NORTHSTAR_CSV", "NORTHSTAR_redcap_export.csv"),
                  ("NORTHSTAR_DICT_CSV", "NORTHSTAR_data_dictionary.csv")]:
    text = (HERE / "data" / name).read_text(encoding="utf-8")
    out.append(f"window.{var} = {json.dumps(text)};")
(HERE / "assets" / "data.js").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote assets/data.js")
